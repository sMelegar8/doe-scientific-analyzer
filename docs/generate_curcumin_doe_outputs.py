"""Generate Curcumin PLARosomes benchmark outputs through the DoE package."""

from __future__ import annotations

from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.doe_analysis import coefficient_table, fit_doe_model, model_metrics, run_pca
from src.utils import ensure_output_dir, load_dataset
from src.visualization import (
    calculate_desirability_region,
    plot_factor_response_map,
    plot_model_r2_summary,
    plot_observed_vs_predicted,
    plot_pareto,
    plot_pca_loadings,
    plot_pca_scores,
    plot_response_profiles,
    plot_response_surface,
    plot_tradeoff_scatter,
    save_figure,
)

DATASET = ROOT / "benchmarks" / "benchmark_public_curcumin_plarosomes.xlsx"
OUTPUT_DIR = ROOT / "outputs" / "curcumin_plarosomes"

FACTORS = ["x1", "x2", "x3"]
RESPONSES = [
    "Y1_particle_size_nm",
    "Y2_drug_release_pct",
    "Y3_entrapment_eff_pct",
]
MODEL_TYPES = {
    "Y1_particle_size_nm": "quadratic",
    "Y2_drug_release_pct": "linear",
    "Y3_entrapment_eff_pct": "linear",
}
LABELS = {
    "x1": "Factor x1",
    "x2": "Factor x2",
    "x3": "Factor x3",
    "Y1_particle_size_nm": "Particle size (nm)",
    "Y2_drug_release_pct": "Drug release (%)",
    "Y3_entrapment_eff_pct": "Entrapment efficiency (%)",
}
GOALS = {
    "Y1_particle_size_nm": "minimize",
    "Y2_drug_release_pct": "maximize",
    "Y3_entrapment_eff_pct": "maximize",
}


def main() -> None:
    """Run the benchmark analysis and save plot/table artifacts."""
    output_dir = ensure_output_dir(OUTPUT_DIR)
    df = load_dataset(DATASET)
    if "Benchmark_Data" not in pd.ExcelFile(DATASET).sheet_names:
        raise ValueError("Expected Benchmark_Data sheet was not found.")
    df = pd.read_excel(DATASET, sheet_name="Benchmark_Data")

    metrics_rows = []
    fitted_models = {}
    for response in RESPONSES:
        model = fit_doe_model(
            df,
            factors=FACTORS,
            response=response,
            model_type=MODEL_TYPES[response],
        )
        fitted_models[response] = model
        coefs = coefficient_table(model)
        metrics = model_metrics(model)
        metrics_rows.append(
            {
                "response": response,
                "model_type": MODEL_TYPES[response],
                **metrics,
            }
        )
        safe = response.lower().replace("_", "-")
        coefs.to_csv(output_dir / f"{safe}_coefficient_table.csv", index=False)
        save_figure(plot_pareto(coefs, label_map=LABELS), output_dir / f"{safe}_pareto.png")
        save_figure(
            plot_observed_vs_predicted(model, label_map=LABELS),
            output_dir / f"{safe}_observed_vs_predicted.png",
        )

    desirability_region = calculate_desirability_region(
        fitted_models,
        goals=GOALS,
        x_factor="x1",
        y_factor="x2",
    )
    for response, model in fitted_models.items():
        safe = response.lower().replace("_", "-")
        save_figure(
            plot_response_surface(
                model,
                "x1",
                "x2",
                label_map=LABELS,
                recommended_region=desirability_region,
            ),
            output_dir / f"{safe}_response_surface_x1_x2.png",
        )

    metrics_df = pd.DataFrame(metrics_rows)
    metrics_df.to_csv(output_dir / "response_model_metrics.csv", index=False)
    save_figure(plot_model_r2_summary(metrics_df, label_map=LABELS), output_dir / "response_model_fit_summary.png")
    save_figure(plot_response_profiles(df, "Run", RESPONSES, label_map=LABELS), output_dir / "multi_response_profiles.png")
    save_figure(
        plot_tradeoff_scatter(
            df,
            "Y1_particle_size_nm",
            "Y2_drug_release_pct",
            "Y3_entrapment_eff_pct",
            label_map=LABELS,
        ),
        output_dir / "multi_response_tradeoff.png",
    )
    save_figure(
        plot_factor_response_map(
            df,
            "x1",
            "x2",
            "Y1_particle_size_nm",
            marker_factor="x3",
            label_map=LABELS,
        ),
        output_dir / "design_space_particle_size.png",
    )

    pca_result = run_pca(df, RESPONSES)
    save_figure(plot_pca_scores(pca_result), output_dir / "pca_scores_responses.png")
    save_figure(plot_pca_loadings(pca_result, label_map=LABELS), output_dir / "pca_loadings_responses.png")

    notice = (
        "Generated by docs/generate_curcumin_doe_outputs.py using the refactored DoE package.\n"
        "Dataset: benchmark_public_curcumin_plarosomes.xlsx / Benchmark_Data.\n"
        "No employer, client, proprietary, or confidential data are used.\n"
    )
    (output_dir / "publication_notice.txt").write_text(notice, encoding="utf-8")
    print(f"Curcumin PLARosomes DoE outputs saved to {output_dir}")


if __name__ == "__main__":
    main()
