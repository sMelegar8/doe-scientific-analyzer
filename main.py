"""Command-line entry point for the clean portfolio/demo DoE workflow."""

from __future__ import annotations

import argparse
from pathlib import Path

from src.doe_analysis import coefficient_table, fit_doe_model, model_metrics, optimize_response, run_pca
from src.utils import ensure_output_dir, load_dataset
from src.visualization import (
    plot_observed_vs_predicted,
    plot_pareto,
    plot_pca_loadings,
    plot_pca_scores,
    plot_response_surface,
    save_figure,
)

DEFAULT_DATASET = "examples/sample_dataset.csv"
DEFAULT_FACTORS = ["temperature_c", "catalyst_pct", "time_min"]
DEFAULT_RESPONSE = "yield_pct"
PUBLICATION_NOTICE = """\
This output was generated by the public portfolio/demo version of the project.
It uses only the dataset supplied through the command line. The bundled example
dataset is synthetic and is not derived from employer, client, thesis, or
confidential laboratory records.
"""


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description="Analyze generic DoE data for process optimization.")
    parser.add_argument("--data", default=DEFAULT_DATASET, help="Path to CSV or Excel input data.")
    parser.add_argument("--factors", nargs="+", default=DEFAULT_FACTORS)
    parser.add_argument("--response", default=DEFAULT_RESPONSE)
    parser.add_argument("--model", choices=["linear", "interaction", "quadratic"], default="quadratic")
    parser.add_argument("--outputs", default="outputs", help="Directory for generated tables and plots.")
    parser.add_argument(
        "--pca-columns",
        nargs="+",
        default=None,
        help="Optional columns for PCA. Defaults to factors plus the selected response.",
    )
    return parser.parse_args()


def main() -> None:
    """Run a complete DoE analysis workflow from the command line."""
    args = parse_args()
    output_dir = ensure_output_dir(args.outputs)

    df = load_dataset(args.data)
    model = fit_doe_model(df, factors=args.factors, response=args.response, model_type=args.model)
    coefs = coefficient_table(model)
    metrics = model_metrics(model)
    optimum, optimum_prediction = optimize_response(model, goal="maximize")

    coefs.to_csv(output_dir / "coefficient_table.csv", index=False)
    (output_dir / "publication_notice.txt").write_text(PUBLICATION_NOTICE, encoding="utf-8")
    (output_dir / "model_metrics.txt").write_text(
        "\n".join(f"{key}: {value:.4f}" for key, value in metrics.items()),
        encoding="utf-8",
    )
    (output_dir / "optimal_parameters.txt").write_text(
        "\n".join([*(f"{key}: {value:.4f}" for key, value in optimum.items()), f"predicted_{args.response}: {optimum_prediction:.4f}"]),
        encoding="utf-8",
    )

    save_figure(plot_pareto(coefs), output_dir / "pareto_chart.png")
    save_figure(plot_observed_vs_predicted(model), output_dir / "observed_vs_predicted.png")
    if len(args.factors) >= 2:
        save_figure(plot_response_surface(model, args.factors[0], args.factors[1]), output_dir / "response_surface.png")

    pca_columns = args.pca_columns or args.factors + [args.response]
    pca_result = run_pca(df, pca_columns)
    save_figure(plot_pca_scores(pca_result), output_dir / "pca_scores.png")
    save_figure(plot_pca_loadings(pca_result), output_dir / "pca_loadings.png")

    print("DoE analysis completed.")
    print(f"Model formula: {model.formula}")
    print(f"Adjusted R2: {metrics['adjusted_r2']:.3f}")
    print(f"Best predicted {args.response}: {optimum_prediction:.3f}")
    print(f"Outputs saved to: {Path(output_dir).resolve()}")


if __name__ == "__main__":
    main()
